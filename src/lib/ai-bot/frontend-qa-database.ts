// Helper functions for Search, Suggestions, and Categories
export class FrontendQAService {
  private static database: FrontendQA[] = FRONTEND_QA_DATABASE;

  public static getAll(): FrontendQA[] {
    return this.database;
  }

  public static getCategories(): QuestionCategory[] {
    return [
      'LFHP Linux Commands',
      'LFHP Networking & Recon',
      'HTML5 & Web Semantics',
      'CSS3 & Modern Styling',
      'Core JavaScript & ES6+',
      'React & Modern Frameworks',
      'Web Performance & Core Vitals',
      'Frontend Security',
      'DOM & Browser APIs',
      'LFHP Lab & Tooling',
    ];
  }

  public static getById(id: string): FrontendQA | undefined {
    return this.database.find(q => q.id === id);
  }

  public static getByCategory(category: QuestionCategory): FrontendQA[] {
    return this.database.filter(q => q.category === category);
  }

  public static getRandom(): FrontendQA {
    const randomIndex = Math.floor(Math.random() * this.database.length);
    return this.database[randomIndex];
  }

  public static getNextSuggestions(currentQA: FrontendQA, count: number = 3): FrontendQA[] {
    const directMatches = (currentQA.suggestedNextIds || [])
      .map(id => this.getById(id))
      .filter((q): q is FrontendQA => q !== undefined);

    if (directMatches.length >= count) {
      return directMatches.slice(0, count);
    }

    // Fill remaining with same category or tags
    const sameCategory = this.database.filter(
      q => q.id !== currentQA.id && 
           !directMatches.some(dm => dm.id === q.id) &&
           q.category === currentQA.category
    );

    const combined = [...directMatches, ...sameCategory];
    if (combined.length >= count) {
      return combined.slice(0, count);
    }

    // Fill with random
    const remaining = this.database.filter(q => q.id !== currentQA.id && !combined.some(c => c.id === q.id));
    return [...combined, ...remaining].slice(0, count);
  }

  /**
   * Smart query matching engine to answer student questions or find closest matches
   */
  public static search(query: string): { results: FrontendQA[]; bestMatch?: FrontendQA } {
    const cleanQuery = query.trim().toLowerCase();
    if (!cleanQuery) {
      return { results: this.database.slice(0, 10), bestMatch: this.database[0] };
    }

    const queryWords = cleanQuery.split(/\s+/).filter(w => w.length > 2);

    const scored = this.database.map(qa => {
      let score = 0;
      const questionLower = qa.question.toLowerCase();
      const answerLower = (qa.shortAnswer + ' ' + qa.detailedAnswer).toLowerCase();
      const tagsString = qa.tags.join(' ').toLowerCase();

      // Exact question match
      if (questionLower === cleanQuery) score += 100;
      else if (questionLower.includes(cleanQuery)) score += 50;

      // Word matching
      queryWords.forEach(word => {
        if (questionLower.includes(word)) score += 15;
        if (tagsString.includes(word)) score += 12;
        if (answerLower.includes(word)) score += 5;
      });

      return { qa, score };
    });

    scored.sort((a, b) => b.score - a.score);

    const filtered = scored.filter(item => item.score > 0).map(item => item.qa);
    const results = filtered.length > 0 ? filtered : this.database.slice(0, 5);
    const bestMatch = scored[0]?.score > 10 ? scored[0].qa : undefined;

    return { results, bestMatch };
  }
}
